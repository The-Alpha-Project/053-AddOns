-- Spell and ability icons (what the classes use) first, then the item icons.
-- The question mark stays first (automatic icon).
function SimpleMacros_SortIcons()
	local first = { SimpleMacros_Icons[1] };
	local rest = {};
	local i, name, head;
	for i = 2, getn(SimpleMacros_Icons) do
		name = SimpleMacros_Icons[i];
		head = strlower(strsub(name, 1, 6));
		if ( head == "spell_" or strlower(strsub(name, 1, 8)) == "ability_" ) then
			tinsert(first, name);
		else
			tinsert(rest, name);
		end
	end
	for i = 1, getn(rest) do
		tinsert(first, rest[i]);
	end
	SimpleMacros_Icons = first;
end
SimpleMacros_SortIcons();
